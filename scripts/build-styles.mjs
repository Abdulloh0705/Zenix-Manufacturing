import {readFile,writeFile} from 'node:fs/promises'
import {resolve} from 'node:path'

// Order matters: tokens → base → primitives → shell → feature modules.
// Sources are plain CSS (no preprocessor); edit them, never the generated src/styles.css.
const root=process.cwd()
const sources=[
  'src/styles/tokens.css',
  'src/styles/base.css',
  'src/shared/ui/styles/controls.css',
  'src/shared/ui/styles/surfaces.css',
  'src/shared/ui/styles/data.css',
  'src/shared/ui/styles/overlays.css',
  'src/layout/AppLayout/shell.css',
  'src/styles/modules.css',
  'src/styles/access.css',
]
const chunks=[]
for(const file of sources)chunks.push(`/* ===== ${file} ===== */\n${(await readFile(resolve(root,file),'utf8')).trim()}\n`)
await writeFile(resolve(root,'src/styles.css'),`/* AUTO-GENERATED by scripts/build-styles.mjs. Edit the source files listed there, not this file. */\n\n${chunks.join('\n')}`)
console.log(`ZENIX Manufacturing styles built from ${sources.length} sources.`)
