import {test,expect} from '@playwright/test'

test('first-time guidance, contextual help, search and tutorial stay read-only',async({page},testInfo)=>{
  await page.goto('/')
  const banner=page.getByLabel('Birinchi kirish yo‘riqnomasi')
  await expect(banner).toBeVisible()
  await expect(banner).toContainText('Biznes egasi')
  await banner.getByRole('button',{name:'Yo‘riqnomani boshlash'}).click()
  await expect(page.getByLabel('Boshlang‘ich yo‘riqnoma')).toBeVisible()
  await page.screenshot({animations:'disabled',path:testInfo.outputPath('help-onboarding.png'),fullPage:true})
  await page.getByRole('button',{name:'Tushundim'}).click()
  await expect(page.getByRole('heading',{name:'Yordam markazi'})).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Birinchi kirish yo‘riqnomasi')).toHaveCount(0)
  await page.goto('/warehouse?view=transfers')
  await expect(page.getByText(/Yuklanmoqda/)).toHaveCount(0)
  await page.getByRole('button',{name:'Yordam',exact:true}).click()
  const panel=page.getByRole('dialog',{name:'Sahifa bo‘yicha yordam'})
  await expect(panel).toContainText('Ombor · Transferlar')
  await expect(panel).toContainText('Sabab majburiy')
  await page.screenshot({animations:'disabled',path:testInfo.outputPath('help-contextual.png'),fullPage:true})
  await panel.getByRole('link',{name:'Yordam markazi'}).click()
  await expect(page).toHaveURL(/\/help\?topic=/)
  const before=await page.evaluate(()=>localStorage.getItem('zenix-manufacturing-v3-state'))
  await page.getByRole('link',{name:'Omborlararo transfer'}).click()
  await expect(page.getByText('Qadam 1 / 3')).toBeVisible()
  await page.getByRole('button',{name:'Keyingi qadam'}).click()
  await expect(page.getByText('Qadam 2 / 3')).toBeVisible()
  await expect.poll(()=>page.evaluate(()=>localStorage.getItem('zenix-manufacturing-v3-state'))).toBe(before)
  await page.getByRole('searchbox',{name:'Yordam qidirish'}).fill('transfer sababi')
  await expect(page.getByRole('region',{name:'Qidiruv natijalari'})).toContainText('Omborlararo transfer')
  await page.screenshot({animations:'disabled',path:testInfo.outputPath('help-center.png'),fullPage:true})
  const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:window.innerWidth}))
  expect(width.scroll).toBeLessThanOrEqual(width.viewport+2)
})

