// ---- Context-aware help and accessibility (2026-11-21) ----
test('keyboard: Yordam panel opens with Enter, keeps Tab inside, closes on Escape and returns focus',async({page},testInfo)=>{
  await page.goto('/warehouse?view=stock')
  await expect(page.getByText(/Yuklanmoqda/)).toHaveCount(0)
  const button=page.getByRole('button',{name:'Yordam',exact:true})
  await button.focus()
  await page.keyboard.press('Enter')
  const panel=page.getByRole('dialog',{name:'Sahifa bo‘yicha yordam'})
  await expect(panel).toBeVisible()
  await expect(button).toHaveAttribute('aria-expanded','true')
  const inside=()=>page.evaluate(()=>Boolean(document.activeElement?.closest('[role="dialog"]')))
  await expect.poll(inside).toBe(true)
  for(let i=0;i<12;i++){await page.keyboard.press('Tab');expect(await inside()).toBe(true)}
  await page.keyboard.press('Shift+Tab');expect(await inside()).toBe(true)
  await expect(panel.getByRole('heading',{name:'Sizning ish kontekstingiz'})).toBeVisible()
  await expect(panel).toContainText('Barcha omborlar')
  await expect(panel).toContainText('Qabul (kirim)')
  await page.screenshot({animations:'disabled',path:testInfo.outputPath('help-context-panel.png')})
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(button).toBeFocused()
  await expect(button).toHaveAttribute('aria-expanded','false')
})

test('keyboard: Help Center search announces results and an opened guide receives focus',async({page})=>{
  await page.goto('/help?q=x')
  const search=page.getByRole('searchbox',{name:'Yordam qidirish'})
  await search.fill('inventarizatsiya')
  await expect(page.locator('#help-search-status')).toHaveText(/\d+ ta natija topildi/)
  const result=page.getByRole('region',{name:'Qidiruv natijalari'}).getByRole('button',{name:/Inventarizatsiya o‘tkazish/})
  await result.focus()
  await expect(result).toBeFocused()
  await page.keyboard.press('Enter')
  const detail=page.getByLabel('Tanlangan yordam mavzusi')
  await expect(detail).toBeFocused()
  await expect(detail.getByRole('heading',{level:2,name:'Inventarizatsiya o‘tkazish'})).toBeVisible()
  await expect(detail.getByRole('note',{name:'Sizning holatingiz'})).toBeVisible()
  await detail.getByRole('button',{name:'Keyingi qadam'}).focus()
  await page.keyboard.press('Enter')
  await expect(detail.getByRole('status')).toHaveText(/Qadam 2 dan 3/)
})

test('a record outside the data is explained, never shown as actionable; layout holds on tablet and phone widths',async({page},testInfo)=>{
  for(const size of [{width:820,height:1180},{width:360,height:780}]){
    await page.setViewportSize(size)
    await page.goto('/equipment?view=maintenance&id=no-such-order')
    await expect(page.getByText(/Yuklanmoqda/)).toHaveCount(0)
    await page.getByRole('button',{name:'Yordam',exact:true}).click()
    const panel=page.getByRole('dialog',{name:'Sahifa bo‘yicha yordam'})
    await expect(panel).toContainText('Ochilgan yozuv topilmadi yoki sizning doirangizdan tashqarida')
    await expect(panel.getByText('Qism berish')).toHaveCount(0)
    // Measured once the slide-in transition has settled.
    await expect.poll(async()=>{const b=await panel.boundingBox();return b?Math.round(b.x+b.width):9999}).toBeLessThanOrEqual(size.width+1)
    expect((await panel.boundingBox())!.x).toBeGreaterThanOrEqual(-1)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2)).toBe(true)
    await page.screenshot({animations:'disabled',path:testInfo.outputPath(`help-missing-record-${size.width}.png`)})
    await page.keyboard.press('Escape')
    await expect(panel).toHaveCount(0)
  }
})
