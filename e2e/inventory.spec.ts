import {test,expect,type Page} from '@playwright/test'
import {openWith,settle,stockedRawStore,stored,watchErrors} from './fixtures'

// Inventory completion: two-step transfer (dispatch → partial receipt) and a stocktaking session, through the real UI.
let errors:ReturnType<typeof watchErrors>
test.beforeEach(({page})=>{errors=watchErrors(page)})
test.afterEach(()=>errors.assertClean())
const noPageOverflow=(page:Page)=>page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+1)
const bal=(s:Awaited<ReturnType<typeof stored>>,itemId:string,wh:string)=>s.stockBalances.find(b=>b.itemId===itemId&&b.warehouseId===wh)

test('transfer goes in transit and is received in part; a stocktaking session is approved as an adjustment',async({page})=>{
  await openWith(page,stockedRawStore(),'/warehouse?view=transfers')
  await page.getByRole('button',{name:'Yangi transfer'}).click()
  const modal=page.getByRole('dialog',{name:'Omborlararo transfer'})
  await modal.locator('.field').filter({hasText:'Qabul qiluvchi ombor'}).locator('.custom-select-trigger').click()
  await page.getByRole('option',{name:'Chirchiq ombori',exact:true}).click()
  await modal.getByLabel('Miqdor',{exact:true}).fill('30')
  expect(await noPageOverflow(page)).toBe(true)
  await modal.getByRole('button',{name:'Yo‘lga chiqarish'}).click()
  await expect(modal.getByText('Transfer sababini yozing (kamida 5 belgi)')).toBeVisible()
  await modal.getByLabel('Transfer sababi').fill('Ishlab chiqarish uchun zaxira')
  await modal.getByRole('button',{name:'Yo‘lga chiqarish'}).click()
  await expect(modal).toBeHidden()
  let s=await stored(page)
  expect([bal(s,'rm2','w1')!.onHand,bal(s,'rm2','w4')!.incoming]).toEqual([20,30])
  expect(s.stockTransfers![0].reason).toBe('Ishlab chiqarish uchun zaxira')
  await page.reload()
  await page.locator('tbody tr').filter({hasText:s.stockTransfers![0].ref}).click()
  const drawer=page.getByRole('dialog').filter({hasText:s.stockTransfers![0].ref})
  await expect(drawer).toContainText('Yo‘lda')
  await expect(drawer).toContainText('Ishlab chiqarish uchun zaxira')
  await expect(drawer).toContainText('Toshkent zavodi / Xomashyo ombori')
  await expect(drawer).toContainText('Chirchiq sexi / Chirchiq ombori')
  await drawer.getByRole('button',{name:'Qabul qilish'}).click()
  const receive=page.getByRole('dialog',{name:'Transferni qabul qilish'})
  await receive.locator('input[type="number"]').first().fill('10')
  await receive.getByRole('button',{name:'Qabulni tasdiqlash'}).click()
  await expect(receive).toBeHidden()
  await expect(drawer).toContainText('Qisman qabul qilindi')
  s=await stored(page)
  expect([bal(s,'rm2','w4')!.onHand,bal(s,'rm2','w4')!.incoming]).toEqual([10,20])
  expect(await noPageOverflow(page)).toBe(true)
  await page.keyboard.press('Escape');await settle(page)

  await page.goto('/warehouse?view=inventory')
  await page.getByRole('button',{name:'Yangi inventarizatsiya'}).click()
  await page.getByRole('dialog',{name:'Yangi inventarizatsiya'}).getByRole('button',{name:'Ochish'}).click()
  const count=page.locator('aside.drawer').filter({hasText:'Inventarizatsiya'})
  await expect(count).toBeVisible()
  await count.getByLabel('M6 bolt sanalgan miqdori').fill('98')
  await count.getByRole('button',{name:/Sanoqni saqlash/}).click()
  await expect(count).toContainText('-2')
  expect(await noPageOverflow(page)).toBe(true)
  await page.setViewportSize({width:820,height:1180})
  expect(await noPageOverflow(page)).toBe(true)
  await count.getByRole('button',{name:'Tasdiqlash'}).click()
  const confirm=page.getByRole('dialog',{name:'Inventarizatsiyani tasdiqlash'})
  await confirm.locator('textarea').fill('E2E oylik sanoq')
  await confirm.getByRole('button',{name:'Tasdiqlash'}).click()
  await expect(count).toContainText('Tasdiqlangan')
  s=await stored(page)
  expect(bal(s,'rm4','w1')!.onHand).toBe(98)
  expect(s.stockCounts![0].status).toBe('Tasdiqlangan')
})

test('immediate transfer records reason, actors and LOT route after refresh',async({page},testInfo)=>{
  await openWith(page,stockedRawStore(),'/warehouse?view=transfers')
  await page.getByRole('button',{name:'Yangi transfer'}).click()
  const modal=page.getByRole('dialog',{name:'Omborlararo transfer'})
  await modal.getByRole('button',{name:'Darhol (bir vaqtda)'}).click()
  await modal.locator('.field').filter({hasText:'Qabul qiluvchi ombor'}).locator('.custom-select-trigger').click()
  await page.getByRole('option',{name:'Chirchiq ombori',exact:true}).click()
  await modal.getByLabel('Miqdor',{exact:true}).fill('5')
  await modal.getByLabel('Transfer sababi').fill('Ishlab chiqarish uchun zaxira')
  await modal.getByRole('button',{name:'Transfer qilish'}).click()
  await expect(modal).toBeHidden()
  const s=await stored(page),t=s.stockTransfers![0]
  expect([t.mode,t.status,t.reason,t.createdBy,t.receipts[0].by,t.fromBranchId,t.toBranchId]).toEqual(['immediate','Qabul qilindi','Ishlab chiqarish uchun zaxira','em1','em1','b1','b2'])
  expect([bal(s,'rm2','w1')!.onHand,bal(s,'rm2','w4')!.onHand]).toEqual([45,5])
  expect(t.lines[0].lot).toBeTruthy()
  await page.reload()
  await page.locator('tbody tr').filter({hasText:t.ref}).click()
  const drawer=page.getByRole('dialog').filter({hasText:t.ref})
  await expect(drawer).toContainText('Ishlab chiqarish uchun zaxira')
  await expect(drawer).toContainText('Darhol ko‘chirildi')
  await expect(drawer).toContainText('Chirchiq sexi / Chirchiq ombori')
  await page.screenshot({path:testInfo.outputPath('immediate-transfer-audit.png'),fullPage:true})
})
